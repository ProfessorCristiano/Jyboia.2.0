# ==========================================
# Exemplo 3: Tabuada Completa com Laço Para (.jy)
# ==========================================

numero = 7

print("Tabuada do", numero)
print("------------------------")

for i in range(1, 11):
    resultado = numero * i
    print(numero, " x ", i, " = ", resultado)

print("------------------------")
print("Fim da Tabuada!")
